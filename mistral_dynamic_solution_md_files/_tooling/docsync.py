#!/usr/bin/env python3
"""docsync (replikit) - replication documentation that stays in step with the code.

Works in any git repository. Every source file in scope gets one Markdown
description under ``<docs>/files/<path>.md`` with two parts:

* a generated FACTS block (between ``docsync:auto`` markers), rewritten on every
  run: size, content hash, imports, imported-by, symbols, routes, tables, env vars;
* a NARRATIVE written by a person or by Claude: purpose, behaviour, nuances,
  how to rebuild it.

The tool never writes narrative. It records the source hash when the narrative
was last reviewed; when the source changes the description is STALE until it is
updated and ``review`` is run. Project-wide section docs declare the files they
describe with ``covers:`` globs and go stale the same way.

Commands
  init [--docs DIR] [--upgrade] [--no-git-hook] [--keep-all-sections]
                         set up replication docs in this repo (detects the stack)
  sync [--prune]         refresh facts, create stubs, mark orphans, rebuild index
  hook                   Claude Code PostToolUse hook (reads hook JSON on stdin)
  status [--all]         list stale / todo docs
  check [--staged]       exit 1 if docs are out of date (pre-commit / CI)
  review PATH... [--note TEXT] [--unchanged]
                         mark descriptions current against the present source
  export [--mode spec|exact] [--out FILE] [--split-mb N] [--max-binary-mb N]
         [--allow-secret PATH...]
                         write a self-contained Markdown bundle for rebuilding
  unpack BUNDLE... --into DIR [--force]
                         recreate every verbatim file from an exact bundle
  verify BUNDLE... --root DIR
                         compare a rebuilt tree with the bundle's hash manifest
  install-git-hook       install the pre-commit hook

Standard library only, Python 3.11+.
"""
