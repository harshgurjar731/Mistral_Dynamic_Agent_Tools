def _out(text: str) -> None:
    """Print without crashing on consoles that cannot encode non-ASCII."""
    try:
        print(text)
    except UnicodeEncodeError:
        print(text.encode("ascii", "replace").decode("ascii"))


def git(*args: str, cwd: Path | None = None, check: bool = True) -> str:
    r = subprocess.run(["git", *args], cwd=cwd or ROOT, capture_output=True)
    if check and r.returncode:
        raise RuntimeError(r.stderr.decode("utf-8", "replace").strip() or f"git {args[0]} failed")
    return r.stdout.decode("utf-8", "replace")


def git_toplevel(start: Path) -> Path | None:
    start = start if start.is_dir() else start.parent
    while not start.exists():
        start = start.parent
    try:
        out = git("rev-parse", "--show-toplevel", cwd=start).strip()
        return Path(out) if out else None
    except Exception:
        return None


def set_root(path: Path | None = None) -> None:
    global ROOT
    env = os.environ.get("DOCSYNC_ROOT")
    base = Path(env) if env else (path or Path.cwd())
    ROOT = git_toplevel(base) or base.resolve()


def find_docs(root: Path) -> Path | None:
    env = os.environ.get("DOCSYNC_DOCS")
    if env:
        p = root / env
        return p if (p / "docsync.toml").exists() else None
    if (root / DEFAULT_DOCS / "docsync.toml").exists():
        return root / DEFAULT_DOCS
    for child in sorted(root.iterdir()) if root.exists() else []:
        if child.is_dir() and (child / "docsync.toml").exists():
            return child
    return None


