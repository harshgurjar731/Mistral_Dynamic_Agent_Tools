    # ---- part 1: sections
    if cfg:
        sec_chunks = ["# Part 1 - Project documentation", ""]
        order = [cfg.docs / "00_INDEX.md"] + sorted(p for p in cfg.docs.rglob("*.md")
                                                     if not p.relative_to(cfg.docs).as_posix().startswith(("files/", "_templates/", "_tooling/"))
                                                     and p.name not in ("00_INDEX.md", "README.md"))
        for p in order:
            if not p.exists():
                continue
            relp = p.relative_to(cfg.docs).as_posix()
            sec_chunks += [f"<!-- replikit:section {relp} -->", shift_headings(strip_fm(p.read_text(encoding="utf-8")), 1), ""]
        chunks.append("\n".join(sec_chunks))

    # ---- part 2: tree
    tree = ["# Part 2 - Repository layout", "", "```text"] + all_files + ["```", ""]
    chunks.append("\n".join(tree))

    # ---- part 3: per-file descriptions (spec) / verbatim payload (exact)
    manifest: list[dict] = []
    withheld: list[tuple[str, str]] = []
    allowed = set(allow_secret)
    if mode == "spec":
        chunks.append("# Part 3 - File descriptions\n")
        scope = set(scoped_files(cfg))
        for rel in all_files:
            data = (ROOT / rel).read_bytes()
            manifest.append({"path": rel, "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data), "included": "description" if rel in scope else "listed"})
