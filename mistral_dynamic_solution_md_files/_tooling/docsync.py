def section_docs(cfg: Config) -> list[Path]:
    out = []
    for p in sorted(cfg.docs.rglob("*.md")):
        relp = p.relative_to(cfg.docs).as_posix()
        if relp.startswith(("files/", "_templates/", "_tooling/")):
            continue
        fm, _ = parse_doc(p.read_text(encoding="utf-8"))
        if fm.get("kind") == "section":
            out.append(p)
    return out


def covers_of(fm: dict) -> list[str]:
    cov = fm.get("covers") or []
    return [cov] if isinstance(cov, str) else cov


def covers_hash(covers: list[str], man: dict) -> tuple[str, int]:
    m = Matcher(covers)
    hashes = [f"{k}:{v['hash']}" for k, v in sorted(man["files"].items()) if m(k)]
    return hashlib.sha256("\n".join(hashes).encode()).hexdigest()[:16], len(hashes)


def refresh_section(cfg: Config, p: Path, man: dict) -> str:
    fm, body = parse_doc(p.read_text(encoding="utf-8"))
    covers = covers_of(fm)
    h, n = covers_hash(covers, man)
    status = "todo" if not fm.get("reviewed_hash") else ("current" if fm["reviewed_hash"] == h else "stale")
    fm["status"] = status
    fm["covers_hash"] = h
    relp = p.relative_to(ROOT).as_posix()
    scope = f"covers {n} files (globs in the front matter)" if covers else "not tied to specific files, so it never goes stale"
    note = {
        "current": f"> **Section status: CURRENT** - reviewed {fm.get('reviewed_on', '')}; {scope}.",
        "stale": f"> **Section status: STALE** - one or more of the {n} covered files changed since this section was reviewed. Re-check it, then run `{tool_cmd(cfg)} review {relp}`.",
        "todo": f"> **Section status: TODO** - not written yet; {scope}. Fill every `_TODO_`, then run `{tool_cmd(cfg)} review {relp}`.",
    }[status]
    write_if_changed(p, dump_doc(fm, replace_auto(body, note)))
    return status


def sections_covering(cfg: Config, rel: str) -> list[Path]:
    hits = []
    for p in section_docs(cfg):
        cov = covers_of(parse_doc(p.read_text(encoding="utf-8"))[0])
        if cov and Matcher(cov)(rel):
            hits.append(p)
    return hits


