def status_line(cfg: Config, status: str, fm: dict, cur_hash: str) -> str:
    rv = fm.get("reviewed_hash") or "-"
    t = tool_cmd(cfg)
    return {
        "current": f"> **Description status: CURRENT** - reviewed {fm.get('reviewed_on', '')} against source `{rv}`.",
        "stale": f"> **Description status: STALE** - the source changed since the description was reviewed (`{rv}` -> `{cur_hash}`). Update the narrative below, then run `{t} review {fm.get('source', '')}`.",
        "todo": f"> **Description status: TODO** - no narrative yet. Fill every `_TODO_` below, then run `{t} review {fm.get('source', '')}`.",
        "orphaned": f"> **Description status: ORPHANED** - the source file no longer exists. Move this description if the file was renamed, or delete it (`{t} sync --prune`).",
    }[status]


def compute_status(fm: dict, cur_hash: str | None) -> str:
    if cur_hash is None:
        return "orphaned"
    if not fm.get("reviewed_hash"):
        return "todo"
    return "current" if fm["reviewed_hash"] == cur_hash else "stale"


def render_auto(cfg: Config, f: Facts, doc: Path, imported_by: list[str], status: str, fm: dict) -> str:
    def dl(rel: str) -> str:
        return f"[{rel}]({rel_link(doc, doc_path(cfg, rel))})"

    out = [status_line(cfg, status, fm, f.hash), "", "| Fact | Value |", "|---|---|",
           f"| Source | [`{f.rel}`]({rel_link(doc, ROOT / f.rel)}) |",
           f"| Kind / language | {f.kind} - {f.lang} |",
           f"| Size | {f.lines} lines - {f.size:,} bytes |" if not f.binary else f"| Size | binary - {f.size:,} bytes |",
           f"| Content hash | `{f.hash}` |", ""]
    if f.summary:
        out += [f"**Self-description (docstring / first heading):** {f.summary}", ""]

    def section(title: str, items: list[str]) -> None:
        if items:
            out.append(f"**{title}**")
            out.extend(f"- {i}" for i in items)
            out.append("")

    section("Defines", f.defines[:80] + (["... (truncated)"] if len(f.defines) > 80 else []))
    section("Routes", f.routes)
    section("Database tables / models", f.tables)
    section("Environment variables / settings read", [f"`{e}`" for e in f.env])
    section("Backend endpoints referenced", [f"`{a}`" for a in f.api_calls])
    section("Imports - internal", [dl(r) for r in f.imports_internal])
    section("Imports - unresolved", [f"`{u}`" for u in f.imports_unresolved])
    if f.imports_external:
        out += ["**Imports - external packages:** " + ", ".join(f"`{e}`" for e in f.imports_external), ""]
    if f.stdlib:
        out += ["**Imports - standard library:** " + ", ".join(f"`{e}`" for e in f.stdlib), ""]
    shown = [dl(r) for r in imported_by[:40]]
    if len(imported_by) > 40:
        shown.append(f"... and {len(imported_by) - 40} more")
    section(f"Imported by ({len(imported_by)})" if imported_by else "Imported by", shown)
    section("Other facts", f.extra)
    return "\n".join(out).rstrip()


def new_doc(cfg: Config, f: Facts) -> tuple[dict, str]:
    t = cfg.templates / f"file.{f.kind}.md"
    if not t.exists():
        t = cfg.templates / "file.code.md"
    tpl = t.read_text(encoding="utf-8").replace("{{source}}", f.rel).replace("{{name}}", Path(f.rel).name) \
        .replace("{{tool}}", tool_cmd(cfg))
    fm, body = parse_doc(tpl)
    fm.update({"source": f.rel, "kind": f.kind, "status": "todo", "reviewed_hash": "", "reviewed_on": "", "narrative_hash": ""})
    return fm, body


def update_file_doc(cfg: Config, f: Facts, imported_by: list[str]) -> tuple[str, bool]:
    doc = doc_path(cfg, f.rel)
    fm, body = parse_doc(doc.read_text(encoding="utf-8")) if doc.exists() else new_doc(cfg, f)
    status = compute_status(fm, f.hash)
    fm["status"] = status
    fm["source_hash"] = f.hash
    body = replace_auto(body, render_auto(cfg, f, doc, imported_by, status, fm))
    return status, write_if_changed(doc, dump_doc(fm, body))


def purpose_of(doc: Path) -> str:
    if not doc.exists():
        return ""
    _, body = parse_doc(doc.read_text(encoding="utf-8"))
    m = re.search(r"^## Purpose\s*\n(.*?)(?=^## |\Z)", narrative_of(body), re.M | re.S)
    if not m:
        return ""
    for line in m.group(1).splitlines():
        line = line.strip()
        if line and not line.startswith("<!--") and TODO_TOKEN not in line:
            return line[:200].replace("|", "/")
    return ""


