_TS_ALIAS_CACHE: dict[str, list[tuple[str, str]]] = {}


def _loose_json(text: str):
    out, i, n, in_str, q = [], 0, len(text), False, ""
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == q:
                in_str = False
        elif c in "\"'":
            in_str, q = True, c
            out.append(c)
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j == -1 else j
            continue
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j == -1 else j + 2
            continue
        else:
            out.append(c)
        i += 1
    s = re.sub(r",\s*([}\]])", r"\1", "".join(out))
    return json.loads(s)


def ts_aliases(rel: str) -> list[tuple[str, str]]:
    """(alias prefix, target dir) pairs from the nearest tsconfig/jsconfig, e.g. ('@/', 'web/src/')."""
    parts = Path(rel).parts
    for i in range(len(parts) - 1, -1, -1):
        d = "/".join(parts[:i])
        cfgs = sorted((ROOT / d).glob("tsconfig*.json")) + sorted((ROOT / d).glob("jsconfig*.json"))
        if not cfgs:
            continue
        if d in _TS_ALIAS_CACHE:
            return _TS_ALIAS_CACHE[d]
        pairs: list[tuple[str, str]] = []
        for c in cfgs:
            try:
                opts = _loose_json(c.read_text(encoding="utf-8")).get("compilerOptions", {})
            except Exception:
                continue
            base = opts.get("baseUrl", ".")
            for alias, targets in (opts.get("paths") or {}).items():
                if not targets:
                    continue
                a = alias.rstrip("*")
                t = os.path.normpath(f"{d}/{base}/{targets[0].rstrip('*')}").replace("\\", "/").lstrip("./")
                if t == ".":
                    t = ""
                pairs.append((a, t + ("/" if t and not t.endswith("/") else "")))
        if not pairs:
            pairs = [("@/", f"{d}/src/".lstrip("/")), ("~/", f"{d}/src/".lstrip("/"))]
        _TS_ALIAS_CACHE[d] = sorted(set(pairs), key=lambda p: -len(p[0]))
        return _TS_ALIAS_CACHE[d]
    return []


def resolve_js(rel: str, spec: str, known: set[str]) -> str | None:
    if spec.startswith("."):
        base = (Path(rel).parent / spec).as_posix()
    else:
        for a, t in ts_aliases(rel):
            if a and spec.startswith(a):
                base = t + spec[len(a):]
                break
        else:
            return None
    base = os.path.normpath(base).replace("\\", "/")
    cands = [base] + [base + e for e in JS_EXT + (".json", ".css", ".scss")] + [f"{base}/index{e}" for e in JS_EXT]
    for c in cands:
        if c in known:
            return c
    return None


def next_route(rel: str) -> str | None:
    p = Path(rel)
    parts = list(p.parts)
    for root in ("app", "pages"):
        if root in parts:
            i = parts.index(root)
            segs = [s for s in parts[i + 1:-1] if not (s.startswith("(") and s.endswith(")"))]
            stem = p.stem
            if root == "app" and stem in ("page", "route"):
                return ("API " if stem == "route" else "page ") + "/" + "/".join(segs)
            if root == "pages" and p.suffix in (".tsx", ".jsx", ".ts", ".js") and not stem.startswith("_"):
                segs = segs + ([] if stem == "index" else [stem])
                return ("API " if segs[:1] == ["api"] else "page ") + "/" + "/".join(segs)
    return None


def js_facts(f: Facts, text: str, known: set[str], deps: set[str]) -> None:
    internal, external, unresolved = set(), set(), set()
    for m in JS_IMPORT.finditer(text):
        spec = next(g for g in m.groups() if g)
        r = resolve_js(f.rel, spec, known)
        if r:
            internal.add(r)
        elif spec.startswith(".") or any(spec.startswith(a) for a, _ in ts_aliases(f.rel) if a):
            unresolved.add(spec)
        else:
            external.add("/".join(spec.split("/")[:2]) if spec.startswith("@") else spec.split("/")[0])
    for m in JS_EXPORT.finditer(text):
        f.defines.append(f"export {'default ' if m.group(1) else ''}{m.group(3)} `{m.group(4)}`")
    f.env = sorted(set(JS_ENV.findall(text)))
    f.routes = [f"page route `{r}`" for r in JS_FILE_ROUTE.findall(text)]
    f.routes += [f"`{m.upper()} {p}`" for m, p in JS_EXPRESS.findall(text)]
    if "next" in deps:
        nr = next_route(f.rel)
        if nr:
            f.routes.append(f"Next.js {nr}")
    f.api_calls = sorted(set(JS_API.findall(text)))
    m = re.match(r"\s*/\*\*?\s*(.+?)\s*(?:\*/|\n)", text)
    if m:
        f.summary = m.group(1).strip("* ")
    f.imports_internal = sorted(internal - {f.rel})
    f.imports_external = sorted(e for e in external if not e.startswith("node:"))
    f.stdlib = sorted(e for e in external if e.startswith("node:"))
    f.imports_unresolved = sorted(unresolved)


