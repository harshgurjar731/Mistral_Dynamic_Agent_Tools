SECRET_PATHS = ["**/*.pem", "**/*.key", "**/*.p12", "**/*.pfx", "**/*.jks", "**/*.keystore", "**/id_rsa*",
                "**/id_ed25519*", "**/id_ecdsa*", "**/*.secret", "**/.env", "**/.env.*", "**/.npmrc", "**/.pypirc",
                "**/credentials*.json", "**/service-account*.json", "**/*.tfstate", "**/*.tfstate.*", "**/.netrc"]
SECRET_SAFE = ["**/.env.example", "**/.env.sample", "**/.env.template", "**/.env.dist", "**/*.example", "**/*.md"]
SECRET_CONTENT = re.compile(
    r"-----BEGIN [A-Z ]*PRIVATE KEY-----|AKIA[0-9A-Z]{16}|\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{24,}|\bghp_[A-Za-z0-9]{30,}"
    r"|\bgithub_pat_[A-Za-z0-9_]{30,}|\bxox[baprs]-[A-Za-z0-9-]{10,}|\bAIza[0-9A-Za-z_-]{35}|\bglpat-[A-Za-z0-9_-]{20}")
BUNDLE_GLOB = "**/*REPLICATION_BUNDLE*.md"
FILE_MARK = re.compile(r"^<!-- replikit:file (\{.*?\}) -->\n(`{3,})[^\n]*\n", re.M)
MANIFEST_MARK = re.compile(r"^<!-- replikit:manifest -->\n(`{3,})json\n(.*?)\n\1$", re.M | re.S)
TOOL_MARK = re.compile(r"^<!-- replikit:tool -->\n(`{3,})python\n(.*?)\n\1$", re.M | re.S)


def fence_for(text: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def lang_tag(rel: str) -> str:
    ext = Path(rel).suffix.lower().lstrip(".")
    return {"py": "python", "ts": "ts", "tsx": "tsx", "js": "js", "jsx": "jsx", "md": "markdown", "yml": "yaml",
            "sh": "bash", "ps1": "powershell", "rs": "rust", "rb": "ruby", "cs": "csharp", "kt": "kotlin"}.get(ext, ext or "text")


def classify_secret(rel: str, data: bytes, allowed: set[str]) -> str | None:
    if rel in allowed:
        return None
    if Matcher(SECRET_PATHS)(rel) and not Matcher(SECRET_SAFE)(rel):
        return "secret-looking file name"
    if b"\0" not in data[:TEXT_SNIFF]:
        m = SECRET_CONTENT.search(data.decode("utf-8", "replace"))
        if m:
            return f"content looks like a credential ({m.group(0)[:6]}...)"
    return None


def encode_file(rel: str, data: bytes) -> tuple[dict, str]:
    meta = {"path": rel, "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
    text = None
    if b"\0" not in data:
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            text = None
    if text is not None:
        crlf, lf_total, cr = text.count("\r\n"), text.count("\n"), text.count("\r")
        if crlf and crlf == lf_total and cr == crlf:
            eol, body = "crlf", text.replace("\r\n", "\n")
        elif cr == 0:
            eol, body = "lf", text
        else:
            text = None  # mixed or bare CR line endings: keep exact bytes
    if text is not None:
        meta.update({"encoding": "text", "eol": eol, "final_newline": body.endswith("\n")})
        content = body if body.endswith("\n") else body + "\n"
        return meta, content
    meta["encoding"] = "base64"
    b64 = base64.b64encode(data).decode("ascii")
    return meta, "\n".join(b64[i:i + 76] for i in range(0, len(b64), 76)) + "\n"


def decode_block(meta: dict, content: str) -> bytes:
    if meta["encoding"] == "base64":
        return base64.b64decode("".join(content.split()))
    body = content
    if not meta.get("final_newline", True) and body.endswith("\n"):
        body = body[:-1]
    if meta.get("eol") == "crlf":
        body = body.replace("\n", "\r\n")
    return body.encode("utf-8")


def strip_fm(text: str) -> str:
    return parse_doc(text)[1]


def shift_headings(text: str, by: int) -> str:
    out, fence = [], None
    for line in text.splitlines():
        m = re.match(r"^(`{3,}|~{3,})", line)
        if m:
            fence = None if fence and line.startswith(fence) else (fence or m.group(1))
        if fence is None and re.match(r"^#{1,6} ", line):
            line = "#" * by + line
        out.append(line)
    return "\n".join(out)


