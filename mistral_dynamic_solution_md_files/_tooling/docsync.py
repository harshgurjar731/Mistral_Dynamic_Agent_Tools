def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="docsync", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", action="version", version=f"docsync {VERSION}")
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init")
    i.add_argument("--docs", default=DEFAULT_DOCS)
    i.add_argument("--upgrade", action="store_true")
    i.add_argument("--no-git-hook", action="store_true")
    i.add_argument("--keep-all-sections", action="store_true")
    s = sub.add_parser("sync")
    s.add_argument("--prune", action="store_true")
    s.add_argument("--quiet", action="store_true")
    sub.add_parser("hook")
    st = sub.add_parser("status")
    st.add_argument("--all", action="store_true")
    c = sub.add_parser("check")
    c.add_argument("--staged", action="store_true")
    r = sub.add_parser("review")
    r.add_argument("paths", nargs="+")
    r.add_argument("--note")
    r.add_argument("--unchanged", action="store_true")
    e = sub.add_parser("export")
    e.add_argument("--mode", choices=["spec", "exact"], default="spec")
    e.add_argument("--out")
    e.add_argument("--split-mb", type=float, default=20)
    e.add_argument("--max-binary-mb", type=float, default=5)
    e.add_argument("--allow-secret", nargs="*", default=[])
    u = sub.add_parser("unpack")
    u.add_argument("bundles", nargs="+")
    u.add_argument("--into", required=True)
    u.add_argument("--force", action="store_true")
    v = sub.add_parser("verify")
    v.add_argument("bundles", nargs="+")
    v.add_argument("--root", required=True)
    v.add_argument("--structure", action="store_true")
    sub.add_parser("install-git-hook")
    a = ap.parse_args(argv)

    if a.cmd == "hook":
        try:
            return cmd_hook()
        except Exception as ex:  # a broken hook must never block the edit itself
            print(f"docsync hook error: {ex}", file=sys.stderr)
            return 0
    if a.cmd == "unpack":
        return cmd_unpack(a.bundles, a.into, a.force)
    if a.cmd == "verify":
        return cmd_verify(a.bundles, a.root, a.structure)
    set_root()
    if a.cmd == "init":
        return cmd_init(a.docs, a.upgrade, not a.no_git_hook, a.keep_all_sections)
    if a.cmd == "export":
        return cmd_export(a.mode, a.out, a.split_mb, a.max_binary_mb, a.allow_secret)
    cfg = require_config()
    if a.cmd == "sync":
        cmd_sync(cfg, a.prune, a.quiet)
        return 0
    if a.cmd == "status":
        return cmd_status(cfg, a.all)
    if a.cmd == "check":
        return cmd_check(cfg, a.staged)
    if a.cmd == "review":
        return cmd_review(cfg, a.paths, a.note, a.unchanged)
    if a.cmd == "install-git-hook":
        return cmd_install_git_hook(cfg)
    return 2


if __name__ == "__main__":
    sys.exit(main())
