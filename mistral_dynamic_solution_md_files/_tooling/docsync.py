HOOK_SCRIPT = """#!/bin/sh
# docsync pre-commit (replikit): refresh replication docs and block commits whose
# staged files have stale descriptions. Installed by `docsync install-git-hook`.
ROOT="$(git rev-parse --show-toplevel)"
PY=""
for c in python3 python py; do
  if command -v "$c" >/dev/null 2>&1 && "$c" -c "import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)" >/dev/null 2>&1; then PY="$c"; break; fi
done
if [ -z "$PY" ]; then echo "docsync: no Python 3.11+ found, skipping doc check" >&2; exit 0; fi
"$PY" "$ROOT/{tool}" sync --quiet || exit 1
git add "$ROOT/{docs}"
"$PY" "$ROOT/{tool}" check --staged
"""


def cmd_install_git_hook(cfg: Config) -> int:
    hooks_dir = git("rev-parse", "--git-path", "hooks").strip()
    target = (ROOT / hooks_dir / "pre-commit") if not Path(hooks_dir).is_absolute() else Path(hooks_dir) / "pre-commit"
    tool = f"{cfg.docs_root}/_tooling/docsync.py"
    if target.exists() and "docsync" not in target.read_text(encoding="utf-8", errors="replace"):
        _out(f"install-git-hook: {target} already exists and is not a docsync hook. Add this to it instead:\n"
             f"  python \"$(git rev-parse --show-toplevel)/{tool}\" sync --quiet && git add {cfg.docs_root} && "
             f"python \"$(git rev-parse --show-toplevel)/{tool}\" check --staged")
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(HOOK_SCRIPT.replace("{tool}", tool).replace("{docs}", cfg.docs_root), encoding="utf-8", newline="\n")
    try:
        target.chmod(0o755)
    except OSError:
        pass
    _out(f"install-git-hook: wrote {target}")
    return 0


def _prune_covers(text: str, files: list[str]) -> tuple[str, int, int]:
    fm, body = parse_doc(text)
    cov = covers_of(fm)
    if not cov:
        return text, 0, 0
    kept = [g for g in cov if any(Matcher([g])(f) for f in files)]
    fm["covers"] = kept
    n = sum(1 for f in files if kept and Matcher(kept)(f))
    return dump_doc(fm, body), len(cov), n


def cmd_init(docs_name: str, upgrade: bool, git_hook: bool, keep_all: bool) -> int:
    if not KIT.exists():
        sys.exit("docsync init must run from the replikit plugin copy (the kit/ folder is missing next to scripts/).")
    if git_toplevel(ROOT) is None:
        sys.exit(f"docsync: {ROOT} is not a git repository. Run `git init` first.")
    existing = find_docs(ROOT)
    docs = existing or ROOT / docs_name
    if existing and not upgrade:
        _out(f"docsync: already initialised at {docs.relative_to(ROOT).as_posix()} - use --upgrade to refresh tooling and templates.")
        return 1
    files = git_files()
    # tooling + templates + README are always (re)written; content docs only on first init
    for sub in ("_templates",):
        shutil.copytree(KIT / sub, docs / sub, dirs_exist_ok=True)
    (docs / "_tooling").mkdir(parents=True, exist_ok=True)
    shutil.copy2(SCRIPT, docs / "_tooling" / "docsync.py")
    shutil.copy2(KIT / "README.md", docs / "README.md")
    report = []
    stack_page = docs / "01_overview" / "00_detected_stack.md"
    if not stack_page.exists():  # generated page added in docsync 2; safe to add on upgrade
        stack_page.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(KIT / "01_overview" / "00_detected_stack.md", stack_page)
    if not existing:
        stack = detect_stack(files)
        for src in sorted(KIT.rglob("*.md")):
            relk = src.relative_to(KIT).as_posix()
            if relk.startswith("_templates/") or relk == "README.md":
                continue
            if relk.endswith("03_ai_models_and_prompts.md") and not stack["llm_sdks"] and not keep_all:
                report.append("- skipped 06_nuances/03_ai_models_and_prompts.md (no LLM SDK detected; add it from the kit if needed)")
                continue
            text = src.read_text(encoding="utf-8")
            text, n_globs, n_files = _prune_covers(text, files)
            dest = docs / relk
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text, encoding="utf-8", newline="\n")
            if n_globs and n_files == 0:
                report.append(f"- {relk}: none of its default `covers:` globs match this repo - set them by hand")
        toml = (KIT / "docsync.toml").read_text(encoding="utf-8")
        media = bulk_media_dirs(files)
        if media:
            extra = "\n".join(f'  "{d}/**",' for d in media)
