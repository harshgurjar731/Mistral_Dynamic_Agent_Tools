def parse_deps(rel: str) -> list[tuple[str, str]]:
    p = ROOT / rel
    name = p.name
    out: list[tuple[str, str]] = []
    try:
        text = p.read_text(encoding="utf-8", errors="replace")
        if name == "package.json":
            d = json.loads(text)
            for sec in ("dependencies", "devDependencies", "peerDependencies"):
                out += [(k, str(v)) for k, v in (d.get(sec) or {}).items()]
        elif name.startswith("requirements") and name.endswith(".txt"):
            for line in text.splitlines():
                line = line.split("#")[0].strip()
                m = re.match(r"^([A-Za-z0-9_.\-\[\]]+)\s*(.*)$", line)
                if m and not line.startswith("-"):
                    out.append((re.sub(r"\[.*\]", "", m.group(1)).lower(), m.group(2).strip()))
        elif name == "pyproject.toml":
            d = tomllib.loads(text)
            for dep in d.get("project", {}).get("dependencies", []):
                m = re.match(r"^([A-Za-z0-9_.\-]+)(.*)$", dep)
                if m:
                    out.append((m.group(1).lower(), m.group(2).strip()))
            for k, v in (d.get("tool", {}).get("poetry", {}).get("dependencies", {}) or {}).items():
                out.append((k.lower(), str(v)))
        elif name == "go.mod":
            out += re.findall(r"^\s*(?:require\s+)?([\w./-]+\.[\w./-]+)\s+(v[\w.\-+]+)", text, re.M)
        elif name == "Cargo.toml":
            d = tomllib.loads(text)
            for k, v in (d.get("dependencies") or {}).items():
                out.append((k, v if isinstance(v, str) else str(v.get("version", ""))))
        elif name == "Gemfile":
            out += [(g, v) for g, v in re.findall(r"^\s*gem\s+['\"]([^'\"]+)['\"](?:\s*,\s*['\"]([^'\"]+))?", text, re.M)]
        elif name == "composer.json":
            d = json.loads(text)
            out += [(k, str(v)) for k, v in (d.get("require") or {}).items()]
        elif name in ("pom.xml",):
            out += [(a, v) for a, v in re.findall(r"<artifactId>([^<]+)</artifactId>\s*(?:<version>([^<]+)</version>)?", text)]
        elif name.endswith((".csproj", ".fsproj")):
            out += re.findall(r'<PackageReference\s+Include="([^"]+)"\s+Version="([^"]+)"', text)
    except Exception:
        pass
    return out


def detect_stack(files: list[str]) -> dict:
    langs: dict[str, int] = {}
    for f in files:
        ext = Path(f).suffix.lower()
        if ext in CODE_EXT:
            langs[lang_of(f)] = langs.get(lang_of(f), 0) + 1
    manifests = [f for f in files if Path(f).name in MANIFESTS or f.endswith((".csproj", ".fsproj"))]
    deps: dict[str, dict[str, str]] = {}
    for m in manifests:
        for name, ver in parse_deps(m):
            deps.setdefault(m, {})[name] = ver
    all_deps = {n for d in deps.values() for n in d}
    frameworks = sorted({label for dep, label in FRAMEWORKS.items()
                         if dep in all_deps or any(d.startswith(dep) for d in all_deps if "/" in dep or "." in dep)})
    llm = sorted(d for d in all_deps if d in LLM_SDKS or d.startswith(("langchain", "@langchain", "llama-index", "@ai-sdk")))
    runtimes: list[str] = []
    for f in files:
        name = Path(f).name
        if name in RUNTIME_FILES:
            runtimes.append(f"`{f}`: {(ROOT / f).read_text(encoding='utf-8', errors='replace').strip()[:80]}")
        elif name.lower().startswith("dockerfile"):
            for v in re.findall(r"^FROM\s+(\S+)", (ROOT / f).read_text(encoding="utf-8", errors="replace"), re.M):
                runtimes.append(f"`{f}`: base image `{v}`")
        elif name == "package.json":
            try:
                eng = json.loads((ROOT / f).read_text(encoding="utf-8")).get("engines")
                if eng:
                    runtimes.append(f"`{f}` engines: {eng}")
            except Exception:
                pass
        elif name == "pyproject.toml":
            try:
                rp = tomllib.loads((ROOT / f).read_text(encoding="utf-8")).get("project", {}).get("requires-python")
                if rp:
                    runtimes.append(f"`{f}` requires-python: {rp}")
            except Exception:
                pass
        elif name == "go.mod":
            m = re.search(r"^go\s+(\S+)", (ROOT / f).read_text(encoding="utf-8"), re.M)
            if m:
                runtimes.append(f"`{f}`: go {m.group(1)}")
    infra = [f for f in files if Path(f).name.lower().startswith(("dockerfile", "docker-compose", "compose."))
             or f.startswith((".github/workflows/", ".gitlab-ci", ".circleci/", "k8s/", "helm/", "charts/"))
             or f.endswith((".tf", "Procfile", "vercel.json", "netlify.toml", "fly.toml", "render.yaml", "app.yaml",
                            "Jenkinsfile", "azure-pipelines.yml", "Caddyfile", "nginx.conf"))]
    entry = [f for f in files if Path(f).name in ("main.py", "app.py", "manage.py", "wsgi.py", "asgi.py", "server.js",
                                                   "server.ts", "index.js", "index.ts", "main.ts", "main.tsx", "main.go",
                                                   "Program.cs", "main.rs", "Application.java", "config.ru")]
    lockfiles = [f for f in files if Path(f).name in ("package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock",
                                                       "bun.lockb", "poetry.lock", "Pipfile.lock", "uv.lock", "go.sum",
                                                       "Cargo.lock", "Gemfile.lock", "composer.lock")]
    return {"languages": dict(sorted(langs.items(), key=lambda kv: -kv[1])), "manifests": manifests, "dependencies": deps,
            "frameworks": frameworks, "llm_sdks": llm, "runtimes": runtimes, "infrastructure": infra,
            "entry_points": entry, "lockfiles": lockfiles}


def bulk_media_dirs(files: list[str]) -> list[str]:
    counts: dict[str, list[int]] = {}
    for f in files:
        parts = f.split("/")[:-1]
        media = Path(f).suffix.lower() in MEDIA_EXT
        for i in range(1, len(parts) + 1):
            c = counts.setdefault("/".join(parts[:i]), [0, 0])
            c[0] += 1
            c[1] += media
    picked: list[str] = []
    for d, (total, media) in sorted(counts.items(), key=lambda kv: kv[0].count("/")):
        if total >= 15 and media / total >= 0.9 and not any(d.startswith(p + "/") for p in picked):
            picked.append(d)
    return picked


def render_stack(cfg: Config, stack: dict) -> str:
    out = ["| | |", "|---|---|",
           "| Languages (code files) | " + (", ".join(f"{k} ({v})" for k, v in stack["languages"].items()) or "-") + " |",
           "| Frameworks / libraries | " + (", ".join(stack["frameworks"]) or "-") + " |",
           "| LLM / AI SDKs | " + (", ".join(f"`{x}`" for x in stack["llm_sdks"]) or "none detected") + " |",
           "| Entry points (by name) | " + (", ".join(f"`{x}`" for x in stack["entry_points"]) or "-") + " |",
           "| Lock files | " + (", ".join(f"`{x}`" for x in stack["lockfiles"]) or "none - versions are not reproducible") + " |", ""]
    if stack["runtimes"]:
        out += ["**Runtime versions found**"] + [f"- {r}" for r in stack["runtimes"]] + [""]
    if stack["infrastructure"]:
        out += ["**Build / deploy / CI files**"] + [f"- `{x}`" for x in stack["infrastructure"]] + [""]
    for m, deps in stack["dependencies"].items():
        out += [f"<details><summary><code>{m}</code> - {len(deps)} dependencies</summary>", ""]
        out += [f"- `{n}` {v}".rstrip() for n, v in deps.items()] + ["", "</details>", ""]
    return "\n".join(out).rstrip()


