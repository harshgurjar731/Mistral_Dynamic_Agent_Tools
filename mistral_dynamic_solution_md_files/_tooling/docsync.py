def _suffix_index(known: set[str]) -> dict[str, str]:
    idx = {}
    for k in known:
        stem = k.rsplit(".", 1)[0]
        idx.setdefault(stem.replace("/", "."), k)
    return idx


_SUFFIX_IDX: dict[str, str] = {}


def resolve_dotted(name: str, known: set[str]) -> str | None:
    global _SUFFIX_IDX
    if not _SUFFIX_IDX:
        _SUFFIX_IDX = _suffix_index(known)
    for key, path in _SUFFIX_IDX.items():
        if key.endswith("." + name) or key == name:
            return path
    return None


def generic_code_facts(f: Facts, text: str, known: set[str], go_module: str) -> None:
    ext = Path(f.rel).suffix.lower()
    imports: list[str] = []
    if ext == ".go":
        block = re.findall(r"^import\s*\((.*?)\)", text, re.S | re.M)
        imports = re.findall(r'"([^"]+)"', " ".join(block)) + re.findall(r'^import\s+(?:\w+\s+)?"([^"]+)"', text, re.M)
        f.defines += [f"func `{n}`" for n in re.findall(r"^func\s+(?:\([^)]*\)\s*)?(\w+)", text, re.M)]
        f.defines += [f"type `{n}` ({k})" for n, k in re.findall(r"^type\s+(\w+)\s+(struct|interface)", text, re.M)]
        f.env = re.findall(r'os\.(?:Getenv|LookupEnv)\(\s*"([^"]+)"', text)
        f.routes = [f"`{m} {p}`" for m, p in re.findall(r'\.(GET|POST|PUT|PATCH|DELETE|Handle|HandleFunc|Get|Post|Put|Delete)\(\s*"(/[^"]*)"', text)]
        for i in imports:
            if go_module and i.startswith(go_module):
                f.extra.append(f"Internal package: `{i[len(go_module):].lstrip('/') or '.'}`")
            elif "." in i.split("/")[0]:
                f.imports_external.append(i)
            else:
                f.stdlib.append(i)
        return
    if ext in (".java", ".kt", ".kts", ".scala"):
        imports = re.findall(r"^import\s+(?:static\s+)?([\w.]+)", text, re.M)
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"\b(class|interface|enum|record|object)\s+(\w+)", text)][:60]
        f.routes = [f"`{m.upper() or 'REQUEST'} {p}`" for m, p in re.findall(r'@(Get|Post|Put|Delete|Patch|Request)Mapping\(\s*(?:value\s*=\s*|path\s*=\s*)?"([^"]*)"', text)]
        f.env = re.findall(r'System\.getenv\(\s*"([^"]+)"', text)
        f.tables = [f"`{t}`" for t in re.findall(r'@Table\(\s*name\s*=\s*"([^"]+)"', text)]
        for i in imports:
            r = resolve_dotted(i, known)
            (f.imports_internal.append(r) if r else f.imports_external.append(".".join(i.split(".")[:2])))
    elif ext == ".cs":
        imports = re.findall(r"^using\s+([\w.]+);", text, re.M)
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"\b(class|interface|enum|record|struct)\s+(\w+)", text)][:60]
        f.routes = [f"`{m.upper()} {p}`" for m, p in re.findall(r'\[Http(Get|Post|Put|Delete|Patch)\(\s*"([^"]*)"', text)]
        f.routes += [f"`ROUTE {p}`" for p in re.findall(r'\[Route\(\s*"([^"]*)"', text)]
        f.routes += [f"`{m.upper()} {p}`" for m, p in re.findall(r'\.Map(Get|Post|Put|Delete|Patch)\(\s*"([^"]*)"', text)]
        f.env = re.findall(r'GetEnvironmentVariable\(\s*"([^"]+)"', text) + re.findall(r'Configuration\[\s*"([^"]+)"\s*\]', text)
        f.imports_external = sorted({i.split(".")[0] for i in imports})
    elif ext == ".rb":
        for spec in re.findall(r"^\s*require_relative\s+['\"]([^'\"]+)['\"]", text, re.M):
            c = os.path.normpath((Path(f.rel).parent / spec).as_posix()).replace("\\", "/")
            c = c if c.endswith(".rb") else c + ".rb"
            (f.imports_internal.append(c) if c in known else f.imports_unresolved.append(spec))
        f.imports_external = re.findall(r"^\s*require\s+['\"]([^'\"]+)['\"]", text, re.M)
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"^\s*(class|module)\s+([\w:]+)", text, re.M)]
        f.defines += [f"def `{n}`" for n in re.findall(r"^\s*def\s+([\w.?!]+)", text, re.M)][:60]
        f.routes = [f"`{m.upper()} {p}`" for m, p in re.findall(r"^\s*(get|post|put|patch|delete|resources?)\s+['\":]([\w/:.-]+)", text, re.M)]
        f.env = re.findall(r"ENV(?:\.fetch\(|\[)\s*['\"]([^'\"]+)['\"]", text)
    elif ext == ".php":
        f.imports_external = sorted({u.split("\\")[0] for u in re.findall(r"^use\s+([\w\\]+)", text, re.M)})
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"\b(class|interface|trait|enum)\s+(\w+)", text)]
        f.defines += [f"function `{n}`" for n in re.findall(r"function\s+(\w+)", text)][:60]
        f.routes = [f"`{m.upper()} {p}`" for m, p in re.findall(r"Route::(get|post|put|patch|delete|any|resource)\(\s*['\"]([^'\"]+)", text)]
        f.env = re.findall(r"(?:getenv|env)\(\s*['\"]([^'\"]+)['\"]", text)
    elif ext == ".rs":
        f.imports_external = sorted({u.split("::")[0] for u in re.findall(r"^use\s+([\w:]+)", text, re.M) if not u.startswith(("crate", "self", "super"))})
        f.extra += [f"Module: `{m}`" for m in re.findall(r"^(?:pub\s+)?mod\s+(\w+)\s*;", text, re.M)]
        f.defines += [f"fn `{n}`" for n in re.findall(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)", text, re.M)][:60]
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"^\s*(?:pub\s+)?(struct|enum|trait)\s+(\w+)", text, re.M)]
        f.routes = [f"`{m.upper()} {p}`" for m, p in re.findall(r'#\[(get|post|put|patch|delete)\(\s*"([^"]+)"', text)]
        f.routes += [f"`ROUTE {p}`" for p in re.findall(r'\.route\(\s*"([^"]+)"', text)]
        f.env = re.findall(r'env::var\(\s*"([^"]+)"', text)
    elif ext == ".sql":
        f.tables = [f"`{t}`" for t in re.findall(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`\"\[]?([\w.]+)", text, re.I)]
    elif ext == ".prisma":
        f.tables = [f"`{t}`" for t in re.findall(r"^model\s+(\w+)\s*\{", text, re.M)]
        f.env = re.findall(r'env\("([^"]+)"\)', text)
    elif ext in (".sh", ".bash", ".ps1", ".bat"):
        f.env = re.findall(r"\$\{?([A-Z_][A-Z0-9_]{2,})", text) + re.findall(r"\$env:([A-Za-z_]\w*)", text)
    elif ext == ".graphql" or ext == ".gql":
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"^(type|input|enum|interface|scalar)\s+(\w+)", text, re.M)]
    elif ext == ".proto":
        f.defines += [f"{k} `{n}`" for k, n in re.findall(r"^(message|service|enum)\s+(\w+)", text, re.M)]
    f.imports_internal = sorted(set(f.imports_internal))
    f.imports_external = sorted(set(f.imports_external))


def other_facts(f: Facts, text: str) -> None:
    p = Path(f.rel)
    ext, name = p.suffix.lower(), p.name
    if ext == ".json":
        try:
            data = json.loads(text)
            if isinstance(data, dict):
                keys = list(data.keys())
                f.extra.append("Top-level keys: " + ", ".join(f"`{k}`" for k in keys[:30]) + (" ..." if len(keys) > 30 else ""))
                if name == "package.json":
                    for sec in ("engines", "scripts", "dependencies", "devDependencies"):
                        if isinstance(data.get(sec), dict):
                            f.extra.append(f"{sec}: " + "; ".join(f"`{k}`: {v}" for k, v in data[sec].items()))
            elif isinstance(data, list):
                f.extra.append(f"JSON array of {len(data)} items")
        except ValueError:
            pass
    elif ext in (".md", ".mdx", ".rst"):
        heads = re.findall(r"^#{1,3} (.+)$", text, re.M)[:15]
        if heads:
            f.summary = heads[0]
            f.extra.append("Headings: " + " | ".join(heads))
    elif ext in (".yaml", ".yml", ".toml"):
        keys = re.findall(r"^\[?([A-Za-z_][\w.-]*)\]?\s*[:=\]]", text, re.M)
        if keys:
            f.extra.append("Top-level keys: " + ", ".join(f"`{k}`" for k in dict.fromkeys(keys)))
        f.env = re.findall(r"\$\{([A-Z_][A-Z0-9_]*)", text)
    elif name.lower().startswith("dockerfile") or ext == ".dockerfile":
        for kw in ("FROM", "EXPOSE", "ENTRYPOINT", "CMD", "WORKDIR"):
            vals = re.findall(rf"^{kw}\s+(.+)$", text, re.M)
            if vals:
                f.extra.append(f"{kw}: " + " | ".join(f"`{v.strip()}`" for v in vals))
        f.env = re.findall(r"^(?:ENV|ARG)\s+([A-Z_][A-Z0-9_]*)", text, re.M)
    elif name.startswith(".env"):
        f.env = re.findall(r"^\s*(?:export\s+)?([A-Z_][A-Z0-9_]*)\s*=", text, re.M)
    elif name.lower() == "makefile":
        f.extra.append("Targets: " + ", ".join(f"`{t}`" for t in re.findall(r"^([\w.-]+):(?!=)", text, re.M)))


@dataclass
class Ctx:
    known: set[str]
    deps: set[str]
    go_module: str


def make_ctx(files: list[str] | None = None) -> Ctx:
    known = set(files if files is not None else git_files())
    deps, go_mod = set(), ""
    for rel in known:
        name = Path(rel).name
        try:
            if name == "package.json":
                d = json.loads((ROOT / rel).read_text(encoding="utf-8"))
                for sec in ("dependencies", "devDependencies", "peerDependencies"):
                    deps.update((d.get(sec) or {}).keys())
            elif name == "go.mod" and not go_mod:
                m = re.search(r"^module\s+(\S+)", (ROOT / rel).read_text(encoding="utf-8"), re.M)
                go_mod = m.group(1) if m else ""
        except Exception:
            pass
    return Ctx(known, deps, go_mod)


def extract(cfg: Config, rel: str, ctx: Ctx) -> Facts:
    data = (ROOT / rel).read_bytes()
    ext = Path(rel).suffix.lower()
    binary = b"\0" in data[:TEXT_SNIFF]
    lines = 0 if binary else data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
    f = Facts(rel=rel, kind="asset" if binary else kind_of(cfg, rel), lang=lang_of(rel), hash=file_hash(data),
              lines=lines, size=len(data), binary=binary)
    if binary:
        return f
    if len(data) > cfg.max_bytes:
        f.extra.append(f"Larger than max_bytes ({cfg.max_bytes}); contents not analysed")
        return f
    text = data.decode("utf-8", "replace")
    try:
        if ext == ".py":
            py_facts(f, text, ctx.known)
        elif ext in JS_EXT:
            js_facts(f, text, ctx.known, ctx.deps)
        elif ext in CODE_EXT:
            generic_code_facts(f, text, ctx.known, ctx.go_module)
        else:
            other_facts(f, text)
    except Exception as e:  # never let one odd file stop a sync
        f.extra.append(f"Fact extraction failed: {type(e).__name__}: {e}")
    f.env = sorted(set(f.env))
    return f


