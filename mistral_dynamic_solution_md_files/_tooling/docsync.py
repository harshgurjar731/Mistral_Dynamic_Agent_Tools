def resolve_py(rel: str, module: str, level: int, known: set[str]) -> str | None:
    parts = Path(rel).parts
    if level:
        base = list(parts[:-1])
        if level > 1:
            base = base[: len(base) - (level - 1)]
        roots = ["/".join(base)]
    else:
        roots = ["/".join(parts[:i]) for i in range(len(parts) - 1, -1, -1)]
    mod_path = module.replace(".", "/") if module else ""
    for r in roots:
        stem = f"{r}/{mod_path}".strip("/") if mod_path else r
        for cand in (f"{stem}.py", f"{stem}/__init__.py"):
            if cand in known:
                return cand
    return None


def py_facts(f: Facts, text: str, known: set[str]) -> None:
    try:
        tree = ast.parse(text)
    except SyntaxError as e:
        f.extra.append(f"Could not parse: {e.msg} (line {e.lineno})")
        return
    doc = ast.get_docstring(tree)
    if doc:
        f.summary = doc.strip().splitlines()[0]
    internal, external, unresolved = set(), set(), set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                r = resolve_py(f.rel, a.name, 0, known)
                internal.add(r) if r else external.add(a.name.split(".")[0])
        elif isinstance(node, ast.ImportFrom):
            mod = node.module or ""
            r = resolve_py(f.rel, mod, node.level, known)
            subs = [resolve_py(f.rel, (mod + "." if mod else "") + a.name, node.level, known) for a in node.names]
            subs = [s for s in subs if s]
            if r:
                internal.add(r)
            internal.update(subs)
            if not r and not subs:
                (unresolved.add("." * node.level + mod) if node.level else external.add(mod.split(".")[0]))
        elif isinstance(node, ast.Call):
            fn = node.func
            fname = ast.unparse(fn)
            if isinstance(fn, ast.Attribute) and fn.attr in ("getenv", "get") and node.args \
                    and ast.unparse(fn.value) in ("os", "os.environ", "environ"):
                a0 = node.args[0]
                if isinstance(a0, ast.Constant) and isinstance(a0.value, str):
                    f.env.append(a0.value)
            elif fname in ("path", "re_path", "url") and node.args and isinstance(node.args[0], ast.Constant) \
                    and Path(f.rel).name == "urls.py":
                view = ast.unparse(node.args[1]) if len(node.args) > 1 else ""
                f.routes.append(f"`{node.args[0].value}` -> `{view}` (Django)")
        elif isinstance(node, ast.Subscript) and ast.unparse(node.value) in ("os.environ", "environ"):
            if isinstance(node.slice, ast.Constant) and isinstance(node.slice.value, str):
                f.env.append(node.slice.value)
    prefix = ""
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            val = node.value
            if isinstance(val, ast.Call) and ast.unparse(val.func).split(".")[-1] in ("APIRouter", "Blueprint"):
                for kw in val.keywords:
                    if kw.arg in ("prefix", "url_prefix") and isinstance(kw.value, ast.Constant):
                        prefix = str(kw.value.value)
            for t in targets:
                if isinstance(t, ast.Name) and t.id.isupper() and len(t.id) > 1:
                    f.defines.append(f"const `{t.id}`")
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            methods = [n.name for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
            line = f"class `{node.name}({bases})`" if bases else f"class `{node.name}`"
            cdoc = ast.get_docstring(node)
            if cdoc:
                line += f" - {cdoc.strip().splitlines()[0]}"
            if methods:
                line += f"  \n  methods: {', '.join(methods[:25])}{' ...' if len(methods) > 25 else ''}"
            f.defines.append(line)
            for n in node.body:
                if isinstance(n, (ast.Assign, ast.AnnAssign)):
                    tgts = n.targets if isinstance(n, ast.Assign) else [n.target]
                    if any(isinstance(t, ast.Name) and t.id == "__tablename__" for t in tgts) and isinstance(n.value, ast.Constant):
                        f.tables.append(f"`{n.value.value}` (model `{node.name}`)")
            if any(b.split(".")[-1] == "Model" for b in bases.split(", ")) and "django" in text:
                f.tables.append(f"`{node.name}` (Django model)")
            if "BaseSettings" in bases:
                for n in node.body:
                    if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name):
                        f.env.append(n.target.id.upper())
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            args = [a.arg for a in node.args.args]
            pre = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
            line = f"{pre} `{node.name}({', '.join(args)})`"
            fdoc = ast.get_docstring(node)
            if fdoc:
                line += f" - {fdoc.strip().splitlines()[0]}"
            f.defines.append(line)
            for d in node.decorator_list:
                if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr in PY_HTTP:
                    path = d.args[0].value if d.args and isinstance(d.args[0], ast.Constant) else ""
                    method = d.func.attr.upper()
                    if method in ("ROUTE", "API_ROUTE"):
                        meths = next((ast.unparse(k.value) for k in d.keywords if k.arg == "methods"), "")
                        method = f"ROUTE{(' ' + meths) if meths else ''}"
                    f.routes.append(f"`{method} {prefix}{path}` -> `{node.name}`")
                dn = ast.unparse(d.func if isinstance(d, ast.Call) else d)
                if dn.endswith(("task", "shared_task")):
                    f.extra.append(f"Background task: `{node.name}` (`@{dn}`)")
    f.imports_internal = sorted(internal - {f.rel})
    f.imports_external = sorted(e for e in external if e not in STDLIB)
    f.stdlib = sorted(e for e in external if e in STDLIB)
    f.imports_unresolved = sorted(unresolved)


