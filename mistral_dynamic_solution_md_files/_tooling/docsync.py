def load_manifest(cfg: Config) -> dict:
    p = manifest_path(cfg)
    if p.exists():
        try:
            return json.loads(p.read_text(encoding="utf-8"))
        except ValueError:
            pass
    return {"files": {}}


def save_manifest(cfg: Config, man: dict) -> None:
    man["files"] = dict(sorted(man["files"].items()))
    write_if_changed(manifest_path(cfg), json.dumps(man, indent=1, sort_keys=True) + "\n")


def reverse_deps(man: dict) -> dict[str, list[str]]:
    rev: dict[str, list[str]] = {}
    for src, info in man["files"].items():
        for dep in info.get("imports", []):
            rev.setdefault(dep, []).append(src)
    return {k: sorted(v) for k, v in rev.items()}


