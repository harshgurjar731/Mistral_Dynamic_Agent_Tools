def cmd_sync(cfg: Config, prune: bool = False, quiet: bool = False) -> dict[str, str]:
    files = scoped_files(cfg)
    ctx = make_ctx()
    facts = {rel: extract(cfg, rel, ctx) for rel in files}
    man = {"version": VERSION, "files": {rel: f.manifest() for rel, f in facts.items()}}
    rev = reverse_deps(man)
    statuses, changed = {}, 0
    for rel, f in facts.items():
        st, ch = update_file_doc(cfg, f, [r for r in rev.get(rel, []) if r in facts])
        statuses[rel] = st
        changed += ch
    orphans = []
    if cfg.files_dir.exists():
        for doc in cfg.files_dir.rglob("*.md"):
            if doc.name == DIR_DOC:
                continue
            src = source_of_doc(cfg, doc)
            if src in facts:
                continue
            if prune:
                doc.unlink()
                continue
            fm, body = parse_doc(doc.read_text(encoding="utf-8"))
            fm["status"] = "orphaned"
            write_if_changed(doc, dump_doc(fm, replace_auto(body, status_line(cfg, "orphaned", fm, ""))))
            orphans.append(src)
        if prune:
            alive = {""} | {"/".join(f.split("/")[:i]) for f in files for i in range(1, len(f.split("/")))}
            for dd in sorted(cfg.files_dir.rglob(DIR_DOC), reverse=True):
                d = dd.parent.relative_to(cfg.files_dir).as_posix()
                if (d if d != "." else "") not in alive:
                    dd.unlink()
            for sub in sorted((p for p in cfg.files_dir.rglob("*") if p.is_dir()), reverse=True):
                if not any(sub.iterdir()):
                    sub.rmdir()
    save_manifest(cfg, man)
    write_dir_docs(cfg, files, statuses)
    write_stack_page(cfg, files)
    sec_status = {p: refresh_section(cfg, p, man) for p in section_docs(cfg)}
    write_index(cfg, files, statuses, sec_status, sorted(orphans))
    if not quiet:
        c = {s: sum(v == s for v in statuses.values()) for s in ("current", "stale", "todo")}
        ss = {s: sum(v == s for v in sec_status.values()) for s in ("current", "stale", "todo")}
        _out(f"docsync: {len(files)} files | {changed} docs written | current {c['current']} | stale {c['stale']} | todo {c['todo']} | orphaned {len(orphans)}")
        _out(f"docsync: {len(sec_status)} sections | current {ss['current']} | stale {ss['stale']} | todo {ss['todo']}")
    return statuses


def to_rel(path_str: str) -> str | None:
    p = Path(path_str)
    if not p.is_absolute():
        p = Path.cwd() / p
    try:
        return p.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return None


def refresh_one(cfg: Config, rel: str) -> tuple[str, bool, Facts]:
    ctx = make_ctx()
    ctx.known.add(rel)
    man = load_manifest(cfg)
    old = set(man["files"].get(rel, {}).get("imports", []))
    is_new = rel not in man["files"]
    f = extract(cfg, rel, ctx)
    man["files"][rel] = f.manifest()
    rev = reverse_deps(man)
    status, _ = update_file_doc(cfg, f, rev.get(rel, []))
    for dep in old ^ set(f.imports_internal):
        if dep in man["files"] and (ROOT / dep).is_file() and in_scope(cfg, dep):
            update_file_doc(cfg, extract(cfg, dep, ctx), rev.get(dep, []))
    save_manifest(cfg, man)
    for s in sections_covering(cfg, rel):
        refresh_section(cfg, s, man)
    return status, is_new, f


def cmd_hook() -> int:
    try:
        payload = json.loads(sys.stdin.read() or "{}")
    except ValueError:
        return 0
    ti = payload.get("tool_input") or {}
    tr = payload.get("tool_response") or {}
    path = ti.get("file_path") or ti.get("notebook_path") or (tr.get("filePath") if isinstance(tr, dict) else None)
    if not path:
        return 0
    p = Path(path)
    if not p.is_absolute():
        p = Path(payload.get("cwd") or os.getcwd()) / p
    set_root(p)
    docs = find_docs(ROOT)
    if docs is None or not p.is_file():
        return 0  # project not using replikit: stay silent
    cfg = load_config(docs)
    rel = to_rel(str(p))
    if rel is None or not in_scope(cfg, rel):
        return 0
    status, is_new, _ = refresh_one(cfg, rel)
    if status == "current" or (status == "todo" and cfg.hook_on_todo == "quiet"):
        return 0
    doc = doc_path(cfg, rel).relative_to(ROOT).as_posix()
    what = ("is new and has no description yet" if is_new else "has no description yet") if status == "todo" \
        else "changed, so its description is now STALE"
    msg = [
        f"docsync: `{rel}` {what}. Its facts block in `{doc}` was refreshed automatically.",
        f"Before finishing this task, update the narrative sections of `{doc}` so they match the code as it is now"
        + (" (fill every `_TODO_`)" if status == "todo" else " (purpose, behaviour, data, config, nuances, rebuild notes - whatever the change affected)")
        + f", then run: {tool_cmd(cfg)} review {rel} --note \"<what changed and why>\"",
        "If the description is still accurate after reading it, run the same command with --unchanged.",
        "Batch this: if you are editing several files, update their descriptions once your code changes are done.",
    ]
    secs = sections_covering(cfg, rel)
    if secs:
        msg.append("Project-level sections that describe this file and may need a matching update: "
                   + ", ".join(f"`{s.relative_to(ROOT).as_posix()}`" for s in secs)
                   + " (mark them with the same review command, passing the section path).")
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "PostToolUse", "additionalContext": "\n".join(msg)}}))
    return 0


def collect_status(cfg: Config) -> tuple[dict[str, str], dict[str, str]]:
    files, out = scoped_files(cfg), {}
    hashes = {r: file_hash((ROOT / r).read_bytes()) for r in files}
    for rel in files:
        doc = doc_path(cfg, rel)
        out[rel] = compute_status(parse_doc(doc.read_text(encoding="utf-8"))[0], hashes[rel]) if doc.exists() else "todo"
    man = {"files": {r: {"hash": h} for r, h in hashes.items()}}
    secs = {}
    for p in section_docs(cfg):
        fm, _ = parse_doc(p.read_text(encoding="utf-8"))
        h, _ = covers_hash(covers_of(fm), man)
        secs[p.relative_to(ROOT).as_posix()] = "todo" if not fm.get("reviewed_hash") else ("current" if fm["reviewed_hash"] == h else "stale")
    return out, secs


def cmd_status(cfg: Config, show_all: bool) -> int:
    files, secs = collect_status(cfg)
    for group in ("stale", "todo"):
        items = [f for f, s in files.items() if s == group]
        _out(f"\n{group.upper()} files: {len(items)}")
        for f in items if (show_all or group == "stale") else items[:20]:
            _out(f"  {f}")
        if group == "todo" and not show_all and len(items) > 20:
            _out(f"  ... {len(items) - 20} more (use --all)")
    _out(f"\nCURRENT files: {sum(s == 'current' for s in files.values())}/{len(files)}")
    _out("\nSections:")
    for s, st in secs.items():
        _out(f"  {st:8} {s}")
    return 0


def cmd_check(cfg: Config, staged: bool) -> int:
    files, secs = collect_status(cfg)
    scope = set(p for p in git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z").split("\0") if p) if staged else set(files)
    stale = sorted(f for f in scope if files.get(f) == "stale")
    todo = sorted(f for f in scope if files.get(f) == "todo")
    stale_secs = [s for s, st in secs.items() if st == "stale"]
    fail = False
    if stale:
        _out(f"docsync: {len(stale)} file description(s) are stale:")
        for f in stale:
            _out(f"  {f}  ->  {doc_path(cfg, f).relative_to(ROOT).as_posix()}")
        fail |= cfg.check_stale == "block"
    if todo:
        _out(f"docsync: {len(todo)} file(s) have no description yet" + (":" if len(todo) <= 15 else " (first 15):"))
        for f in todo[:15]:
            _out(f"  {f}")
        fail |= cfg.check_todo == "block"
    if stale_secs:
        _out("docsync: stale sections:\n  " + "\n  ".join(stale_secs))
        fail |= cfg.check_stale == "block"
    if fail:
        _out(f"\nUpdate the descriptions, then run: {tool_cmd(cfg)} review <path> --note \"...\"")
        return 1
    return 0


def cmd_review(cfg: Config, paths: list[str], note: str | None, unchanged: bool) -> int:
    rc = 0
    today = _dt.date.today().isoformat()
    docs_rel = cfg.docs_root
    for raw in paths:
        rel = to_rel(raw) or raw.replace("\\", "/")
        if rel.startswith(f"{docs_rel}/files/") and rel.endswith(".md"):
            rel = source_of_doc(cfg, ROOT / rel)
        is_section = rel.startswith(docs_rel + "/")
        if is_section:
            doc = ROOT / rel
            if not doc.exists():
                _out(f"review: no such section {rel}")
                rc = 1
                continue
            fm, body = parse_doc(doc.read_text(encoding="utf-8"))
            man = {"files": {r: {"hash": file_hash((ROOT / r).read_bytes())} for r in scoped_files(cfg)}}
            new_hash, _ = covers_hash(covers_of(fm), man)
        else:
            src = ROOT / rel
            if not src.is_file():
                _out(f"review: {rel} is not a file")
                rc = 1
                continue
            doc = doc_path(cfg, rel)
            if not doc.exists():
                refresh_one(cfg, rel)
            fm, body = parse_doc(doc.read_text(encoding="utf-8"))
            new_hash = file_hash(src.read_bytes())
        shown = doc.relative_to(ROOT).as_posix()
        if TODO_TOKEN in re.sub(r"<!--.*?-->", "", narrative_of(body), flags=re.S):
            _out(f"review: {shown} still contains {TODO_TOKEN} placeholders - fill them (write 'None' or 'n/a' where nothing applies).")
            rc = 1
            continue
        if fm.get("status") == "stale" and not unchanged and fm.get("narrative_hash") == narrative_hash(body):
            _out(f"review: {shown} - source changed but the description did not. Update it, or pass --unchanged if it is still accurate.")
            rc = 1
            continue
        if note:
            entry = f"- {today} - `{new_hash[:8]}` - {note}"
            if re.search(r"^## Change log\s*$", body, re.M):
                body = re.sub(r"(^## Change log\s*\n(?:<!--.*?-->\s*\n)?)", lambda m: m.group(1) + entry + "\n", body, count=1, flags=re.M | re.S)
            else:
                body = body.rstrip() + f"\n\n## Change log\n{entry}\n"
        fm.update({"reviewed_hash": new_hash, "reviewed_on": today, "status": "current", "narrative_hash": narrative_hash(body)})
        write_if_changed(doc, dump_doc(fm, body))
        if is_section:
            refresh_section(cfg, doc, load_manifest(cfg))
        else:
            refresh_one(cfg, rel)
        _out(f"review: {rel} marked current ({new_hash[:8]})")
    return rc


