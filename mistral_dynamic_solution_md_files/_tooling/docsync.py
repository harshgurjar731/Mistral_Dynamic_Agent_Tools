def write_dir_docs(cfg: Config, files: list[str], statuses: dict[str, str]) -> None:
    dirs: dict[str, dict] = {"": {"files": [], "dirs": set()}}
    for rel in files:
        parts = rel.split("/")
        for i in range(len(parts)):
            d = "/".join(parts[:i])
            dirs.setdefault(d, {"files": [], "dirs": set()})
            if i < len(parts) - 1:
                dirs[d]["dirs"].add("/".join(parts[: i + 1]))
        dirs["/".join(parts[:-1])]["files"].append(rel)
    tpl = (cfg.templates / "directory.md").read_text(encoding="utf-8")
    for d, info in dirs.items():
        doc = cfg.files_dir / d / DIR_DOC if d else cfg.files_dir / DIR_DOC
        if doc.exists():
            fm, body = parse_doc(doc.read_text(encoding="utf-8"))
        else:
            fm, body = parse_doc(tpl.replace("{{dir}}", d or "(repository root)"))
            fm["directory"] = d or "."
        below = [f for f in files if d == "" or f.startswith(d + "/")]
        c = {s: sum(statuses.get(f, "todo") == s for f in below) for s in ("current", "stale", "todo")}
        lines = [f"> {len(below)} files below this folder - current {c['current']}, stale {c['stale']}, todo {c['todo']}.", ""]
        if info["dirs"]:
            lines += ["| Sub-folder | Files | Purpose |", "|---|---|---|"]
            for sd in sorted(info["dirs"]):
                sdoc = cfg.files_dir / sd / DIR_DOC
                n = sum(1 for f in files if f.startswith(sd + "/"))
                lines.append(f"| [{Path(sd).name}/]({rel_link(doc, sdoc)}) | {n} | {purpose_of(sdoc) or '-'} |")
            lines.append("")
        if info["files"]:
            lines += ["| File | Status | Purpose |", "|---|---|---|"]
            for f in sorted(info["files"]):
                fdoc = doc_path(cfg, f)
                lines.append(f"| [{Path(f).name}]({rel_link(doc, fdoc)}) | {statuses.get(f, 'todo')} | {purpose_of(fdoc) or '-'} |")
        write_if_changed(doc, dump_doc(fm, replace_auto(body, "\n".join(lines))))


def write_index(cfg: Config, files: list[str], statuses: dict[str, str], sec_status: dict[Path, str], orphans: list[str]) -> None:
    idx = cfg.docs / "00_INDEX.md"
    if not idx.exists():
        return
    fm, body = parse_doc(idx.read_text(encoding="utf-8"))
    total = len(files)
    c = {s: sum(statuses.get(f) == s for f in files) for s in ("current", "stale", "todo")}
    pct = (100 * c["current"] // total) if total else 0
    sc = {s: sum(v == s for v in sec_status.values()) for s in ("current", "stale", "todo")}
    lines = [f"**File descriptions:** {c['current']}/{total} current ({pct}%) - {c['stale']} stale - {c['todo']} todo - {len(orphans)} orphaned  ",
             f"**Sections:** {sc['current']}/{len(sec_status)} current - {sc['stale']} stale - {sc['todo']} todo", ""]
    areas: dict[str, list[str]] = {}
    for f in files:
        areas.setdefault(f.split("/")[0] if "/" in f else "(root files)", []).append(f)
    lines += ["| Area | Files | Current | Stale | Todo |", "|---|---|---|---|---|"]
    for a, fs in sorted(areas.items()):
        link = f"[{a}](files/{a}/{DIR_DOC})" if a != "(root files)" else f"[{a}](files/{DIR_DOC})"
        lines.append(f"| {link} | {len(fs)} | {sum(statuses.get(x) == 'current' for x in fs)} | "
                     f"{sum(statuses.get(x) == 'stale' for x in fs)} | {sum(statuses.get(x) == 'todo' for x in fs)} |")
    lines += ["", "| Section | Status |", "|---|---|"]
    for p, s in sec_status.items():
        r = p.relative_to(cfg.docs).as_posix()
        lines.append(f"| [{r}]({r}) | {s} |")
    stale = [f for f in files if statuses.get(f) == "stale"]
    if stale:
        lines += ["", "**Stale descriptions (fix first):**"] + [f"- [{f}](files/{f}.md)" for f in stale]
    if orphans:
        lines += ["", "**Orphaned descriptions:**"] + [f"- `{o}`" for o in orphans]
    write_if_changed(idx, dump_doc(fm, replace_auto(body, "\n".join(lines))))


