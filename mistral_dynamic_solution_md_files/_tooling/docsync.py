def parse_doc(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    raw, body = text[3:end].strip("\n"), text[end + 4:].lstrip("\n")
    fm: dict = {}
    key = None
    for line in raw.splitlines():
        if re.match(r"^\s+-\s", line) and key:
            if not isinstance(fm.get(key), list):
                fm[key] = []
            fm[key].append(line.split("-", 1)[1].strip().strip('"'))
            continue
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            key, val = m.group(1), m.group(2).strip()
            fm[key] = [] if val == "" else val.strip('"')
    return fm, body


def dump_doc(fm: dict, body: str) -> str:
    lines = ["---"]
    for k, v in fm.items():
        if isinstance(v, list):
            lines.append(f"{k}:")
            lines += [f'  - "{x}"' for x in v]
        else:
            lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n" + body.rstrip() + "\n"


def narrative_of(body: str) -> str:
    return AUTO_RE.sub("", body).strip()


def narrative_hash(body: str) -> str:
    return hashlib.sha256(narrative_of(body).encode()).hexdigest()[:16]


def replace_auto(body: str, auto: str) -> str:
    block = f"{AUTO_BEGIN}\n{auto.rstrip()}\n{AUTO_END}"
    if AUTO_RE.search(body):
        body = AUTO_RE.sub(lambda _: block, body, count=1)
    else:
        m = re.search(r"^# .*$", body, re.M)
        if m:
            body = body[: m.end()] + "\n\n" + block + "\n\n" + body[m.end():].lstrip("\n")
        else:
            body = block + "\n\n" + body
    return re.sub(re.escape(AUTO_END) + r"\n{3,}", AUTO_END + "\n\n", body)


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


