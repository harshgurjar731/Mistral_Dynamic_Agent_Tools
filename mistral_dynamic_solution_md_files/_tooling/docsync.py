@dataclass
class Config:
    docs: Path
    include: list[str] = field(default_factory=lambda: ["**"])
    exclude: list[str] = field(default_factory=list)
    max_bytes: int = 1_000_000
    hook_on_todo: str = "prompt"
    check_stale: str = "block"
    check_todo: str = "warn"
    kinds: dict[str, list[str]] = field(default_factory=dict)
    export_exclude: list[str] = field(default_factory=list)

    @property
    def docs_root(self) -> str:
        return self.docs.relative_to(ROOT).as_posix()

    @property
    def files_dir(self) -> Path:
        return self.docs / "files"

    @property
    def templates(self) -> Path:
        t = self.docs / "_templates"
        return t if t.exists() else KIT / "_templates"


def load_config(docs: Path) -> Config:
    cfg = Config(docs=docs)
    data = tomllib.loads((docs / "docsync.toml").read_text(encoding="utf-8"))
    cfg.include = data.get("include", cfg.include)
    cfg.exclude = list(data.get("exclude", []))
    cfg.max_bytes = data.get("max_bytes", cfg.max_bytes)
    cfg.hook_on_todo = data.get("hook", {}).get("on_todo", cfg.hook_on_todo)
    cfg.check_stale = data.get("check", {}).get("stale", cfg.check_stale)
    cfg.check_todo = data.get("check", {}).get("todo", cfg.check_todo)
    cfg.kinds = data.get("kinds", {})
    cfg.export_exclude = data.get("export", {}).get("exclude", [])
    cfg.exclude.append(f"{cfg.docs_root}/**")  # the docs never document themselves
    cfg.exclude.append("**/*REPLICATION_BUNDLE*.md")  # nor exported bundles
    return cfg


def require_config() -> Config:
    docs = find_docs(ROOT)
    if docs is None:
        sys.exit(f"docsync: no replication docs in {ROOT} - run `docsync init` first.")
    return load_config(docs)


def glob_to_re(pattern: str) -> re.Pattern:
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif pattern.startswith("**", i):
            out += ".*"
            i += 2
        elif pattern[i] == "*":
            out += "[^/]*"
            i += 1
        elif pattern[i] == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(pattern[i])
            i += 1
    return re.compile(out + r"\Z", re.I)


class Matcher:
    def __init__(self, patterns: list[str]):
        self.res = [glob_to_re(p) for p in patterns]

    def __call__(self, path: str) -> bool:
        return any(r.match(path) for r in self.res)


def git_files() -> list[str]:
    out = git("ls-files", "--cached", "--others", "--exclude-standard", "-z")
    return sorted({p for p in out.split("\0") if p and (ROOT / p).is_file()})


def in_scope(cfg: Config, rel: str) -> bool:
    return Matcher(cfg.include)(rel) and not Matcher(cfg.exclude)(rel)


def scoped_files(cfg: Config) -> list[str]:
    inc, exc = Matcher(cfg.include), Matcher(cfg.exclude)
    return [p for p in git_files() if inc(p) and not exc(p)]


